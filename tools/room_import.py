"""Turn the artist's wall and floor deliveries into the den's wallpaper and floor layers.

    python tools/room_import.py --manifest tools/room_styles.json

The den is drawn as two layers: a WALL (a whole-room image: back wall, side walls,
window, shelves, lamp) with a FLOOR on top of it, cut to the room's floor outline. So any
wall goes with any floor. What makes that work is that every delivery is painted to the
same room template (see "template" in the manifest): the same corners, the same floor
line, the window and both shelves in the same spots. The shelves matter most, because
den.gd lands finds on them at fixed heights (BAKED_SHELVES).

What it does:
  1. Walls: checked for size and saved as WebP, a tenth the size of her JPEGs with no
     visible difference. A wall's own painted floor doesn't matter: the floor layer
     covers it.
  2. Floors: cut to the floor outline, everything above it made transparent, saved as
     WebP (it keeps the transparency at a fraction of a PNG's size).
  3. Writes src/world/room_catalog.gd, the list the game picks from.
  4. Writes review sheets to build/room_sheets/: every wall's shelves next to the
     template's, every wall with the default floor (the seams), every floor on the
     default wall. The shelf check is by eye, on purpose: matching a shelf against a
     busy wallpaper by computer is unreliable, and a person spots it in a second.

The deliveries sit in assets/main_menu/backgrounds/ and assets/main_menu/Floors/, each
with a .gdignore so Godot doesn't import 40-odd full-size images into the build. The
game only loads what this writes.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parent.parent
SUPERSAMPLE = 4


def floor_mask(size: tuple[int, int], outline: list, lift: int) -> Image.Image:
    """The floor region as an 8-bit mask: below the outline, smooth-edged.

    Drawn at 4x and shrunk, so the edge is antialiased; the room is painted art, not
    pixel art, so a soft edge is what matches it. `lift` raises it a couple of pixels
    so the floor's own seam shadow is kept and no sliver of wall shows under it.
    """
    w, h = size
    big = Image.new("L", (w * SUPERSAMPLE, h * SUPERSAMPLE), 0)
    pts = [(x * SUPERSAMPLE, (y - lift) * SUPERSAMPLE) for x, y in outline]
    pts += [(w * SUPERSAMPLE, h * SUPERSAMPLE), (0, h * SUPERSAMPLE)]
    ImageDraw.Draw(big).polygon(pts, fill=255)
    return big.resize((w, h), Image.LANCZOS)


def fit_to_template(im: Image.Image, size: tuple[int, int], name: str, problems: list) -> Image.Image | None:
    """The template size, or a centred crop when a delivery is a few pixels over."""
    if im.size == tuple(size):
        return im
    w, h = size
    if h == im.height and 0 < im.width - w <= 16:
        left = (im.width - w) // 2
        print(f"  {name}: {im.width}x{im.height}, cropped {left}px off each side to {w}x{h}")
        return im.crop((left, 0, left + w, h))
    problems.append(f"{name}: {im.width}x{im.height}, the room is {w}x{h}")
    return None


def gd_string(text: str) -> str:
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def write_catalog(path: Path, manifest: dict, walls: list, floors: list) -> None:
    def rows(entries: list) -> str:
        return "\n".join(
            f'\t{{"id": {gd_string(e["id"])}, "label": {gd_string(e["label"])}, '
            f'"texture": {gd_string(e["res"])}}},'
            for e in entries
        )

    path.write_text(
        f"""# GENERATED by tools/room_import.py from tools/room_styles.json. Don't edit by hand:
# change the manifest and re-run the import.
class_name RoomCatalog
extends RefCounted

## The den's wallpapers and floors. A wall is a whole-room image; a floor is the floor
## alone, transparent above the floor line, drawn on top of the wall.

const DEFAULT_WALL := {gd_string(manifest["default_wall"])}
const DEFAULT_FLOOR := {gd_string(manifest["default_floor"])}

const WALLS := [
{rows(walls)}
]

const FLOORS := [
{rows(floors)}
]


static func wall(id: String) -> Dictionary:
	return _find(WALLS, id, DEFAULT_WALL)


static func floor(id: String) -> Dictionary:
	return _find(FLOORS, id, DEFAULT_FLOOR)


## The entry for `id`, or the default's if there's no such entry: a save can outlive a
## wallpaper that was renamed or dropped, and should land on something, not nothing.
static func _find(list: Array, id: String, fallback: String) -> Dictionary:
	for entry in list:
		if entry["id"] == id:
			return entry
	for entry in list:
		if entry["id"] == fallback:
			return entry
	return {{}}
""",
        encoding="utf-8",
        newline="\n",
    )


def labelled(im: Image.Image, label: str) -> Image.Image:
    out = Image.new("RGB", (im.width, im.height + 16), (255, 255, 255))
    out.paste(im.convert("RGB"), (0, 16))
    ImageDraw.Draw(out).text((3, 2), label, fill=(0, 0, 0))
    return out


def grid(tiles: list, cols: int) -> Image.Image:
    w = max(t.width for t in tiles)
    h = max(t.height for t in tiles)
    rows = (len(tiles) + cols - 1) // cols
    sheet = Image.new("RGB", (w * cols, h * rows), (255, 255, 255))
    for i, t in enumerate(tiles):
        sheet.paste(t, ((i % cols) * w, (i // cols) * h))
    return sheet


def write_sheets(dest: Path, template: dict, walls: list, floors: list, default_wall, default_floor) -> None:
    dest.mkdir(parents=True, exist_ok=True)
    outline = template["floor_outline"]

    # Shelves: the area around both shelves, with the template's shelf tops in magenta.
    sx0, sy0, sx1, sy1 = template["shelf_review_box"]
    tiles = []
    for e in walls:
        crop = e["image"].crop((sx0, sy0, sx1, sy1)).convert("RGB")
        d = ImageDraw.Draw(crop)
        for x, y, width in template["shelves"]:
            d.line([(x - sx0, y - sy0), (x - sx0 + width, y - sy0)], fill=(255, 0, 255), width=2)
        tiles.append(labelled(crop.resize((crop.width // 2, crop.height // 2)), e["id"]))
    grid(tiles, 6).save(dest / "walls_shelves.png")

    # Seams: every wall under the default floor, at the two corners and the middle.
    boxes = [(0, 560, 700, 960), (1600, 560, 2300, 960), (3204, 560, 3904, 960)]
    tiles = []
    for e in walls:
        room = e["image"].convert("RGBA")
        room.alpha_composite(default_floor["image"])
        strip = Image.new("RGB", (700 * 3, 400))
        for i, b in enumerate(boxes):
            strip.paste(room.crop(b).convert("RGB"), (700 * i, 0))
        tiles.append(labelled(strip.resize((strip.width // 3, strip.height // 3)), e["id"]))
    grid(tiles, 3).save(dest / "walls_seams.png")

    # Floors on the default wall, whole room, small.
    tiles = []
    for e in floors:
        room = default_wall["image"].convert("RGBA")
        room.alpha_composite(e["image"])
        tiles.append(labelled(room.resize((650, 181)).convert("RGB"), e["id"]))
    grid(tiles, 3).save(dest / "floors.png")
    print(f"Review sheets in {dest}")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--manifest", type=Path, required=True)
    parser.add_argument("--no-sheets", action="store_true", help="skip the review sheets")
    args = parser.parse_args()

    manifest = json.loads(args.manifest.read_text(encoding="utf-8"))
    template = manifest["template"]
    size = tuple(template["size"])
    walls_src = ROOT / manifest["walls_src"]
    floors_src = ROOT / manifest["floors_src"]
    walls_out = ROOT / manifest["walls_out"]
    floors_out = ROOT / manifest["floors_out"]
    walls_out.mkdir(parents=True, exist_ok=True)
    floors_out.mkdir(parents=True, exist_ok=True)
    mask = floor_mask(size, template["floor_outline"], template.get("floor_mask_lift", 0))

    problems: list[str] = []
    walls, floors = [], []
    written: set[Path] = set()

    for spec in manifest["walls"]:
        if spec.get("skip"):
            print(f"  wall {spec['id']}: skipped ({spec['skip']})")
            continue
        src = walls_src / spec["src"]
        im = fit_to_template(Image.open(src), size, spec["id"], problems)
        if im is None:
            continue
        out = walls_out / f"{spec['id']}.webp"
        im.convert("RGB").save(out, quality=90, method=6)
        written.add(out)
        walls.append({**spec, "res": "res://" + out.relative_to(ROOT).as_posix(), "image": im.convert("RGB")})

    for spec in manifest["floors"]:
        if spec.get("skip"):
            print(f"  floor {spec['id']}: skipped ({spec['skip']})")
            continue
        src = floors_src / spec["src"]
        im = fit_to_template(Image.open(src), size, spec["id"], problems)
        if im is None:
            continue
        layer = im.convert("RGB").convert("RGBA")
        layer.putalpha(mask)
        out = floors_out / f"{spec['id']}.webp"
        layer.save(out, quality=90, method=6)
        written.add(out)
        floors.append({**spec, "res": "res://" + out.relative_to(ROOT).as_posix(), "image": layer})

    # Anything left in the output folders from an entry that's since been dropped.
    for folder in (walls_out, floors_out):
        for f in folder.iterdir():
            if f.suffix in (".jpg", ".png", ".webp") and f not in written:
                print(f"  removing {f.relative_to(ROOT)} (no longer in the manifest)")
                f.unlink()

    ids = {e["id"] for e in walls}
    if manifest["default_wall"] not in ids:
        problems.append(f"default_wall '{manifest['default_wall']}' isn't an imported wall")
    if manifest["default_floor"] not in {e["id"] for e in floors}:
        problems.append(f"default_floor '{manifest['default_floor']}' isn't an imported floor")

    write_catalog(ROOT / manifest["catalog"], manifest, walls, floors)
    print(f"{len(walls)} walls, {len(floors)} floors -> {manifest['catalog']}")

    if not args.no_sheets and walls and floors:
        default_wall = next(e for e in walls if e["id"] == manifest["default_wall"])
        default_floor = next(e for e in floors if e["id"] == manifest["default_floor"])
        write_sheets(ROOT / "build" / "room_sheets", template, walls, floors, default_wall, default_floor)

    for p in problems:
        print(f"PROBLEM: {p}")
    if problems:
        raise SystemExit(1)


if __name__ == "__main__":
    main()
